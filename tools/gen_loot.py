"""Bake XP4Life art into terminal Raster cells (half-block pixel art).

Usage: python tools/gen_loot.py <XP4Life Assets dir> assets/emblem-terminal.png hooks/loot.ts

Reward art is resized from the curated rewards; the emblem is grid pixel art,
sampled block for block so it stays exact. Also writes assets/emblem.txt, the
emblem as plain text for places without color.
"""
import base64, glob, json, os, re, struct, sys
from PIL import Image, ImageEnhance

ASSETS, EMBLEM_PNG, OUT = sys.argv[1], sys.argv[2], sys.argv[3]
SIZE = 24  # reward art: 24 pixels square -> 24 columns x 12 rows of half blocks
DEFAULT = 0x01000000
UPPER, LOWER, FULL = 0x2580, 0x2584, 0x2588


def field(text, name):
    m = re.search(rf'^{name}:\s*"?([^"\n]*)"?\s*$', text, re.M)
    return m.group(1).strip() if m else ""


def cells_of(grid):
    """Pairs of pixel rows -> Raster words: upper half block, fg on top, bg below."""
    words = []
    for r in range(len(grid) // 2):
        for top, bot in zip(grid[r * 2], grid[r * 2 + 1]):
            if top is None and bot is None:
                words += [0x20, DEFAULT, DEFAULT]
            elif bot is None:
                words += [UPPER, top, DEFAULT]
            elif top is None:
                words += [LOWER, bot, DEFAULT]
            else:
                words += [UPPER, top, bot]
    return base64.b64encode(struct.pack(f"<{len(words)}I", *words)).decode()


def text_of(grid):
    shape = {(False, False): " ", (True, False): chr(UPPER), (False, True): chr(LOWER), (True, True): chr(FULL)}
    return "\n".join(
        "".join(shape[(t is not None, b is not None)] for t, b in zip(grid[r * 2], grid[r * 2 + 1])).rstrip()
        for r in range(len(grid) // 2)
    )


def bake(path, crop=0.04):
    """Painted art: crop, shrink, lift contrast, and drop the background color."""
    im = Image.open(path).convert("RGB")
    w, h = im.size
    im = im.crop((int(w * crop), int(h * crop), int(w * (1 - crop)), int(h * (1 - crop))))
    im = im.resize((SIZE, SIZE), Image.LANCZOS)
    im = ImageEnhance.Color(ImageEnhance.Contrast(im).enhance(1.35)).enhance(1.25)
    px = im.load()
    corners = [px[0, 0], px[SIZE - 1, 0], px[0, SIZE - 1], px[SIZE - 1, SIZE - 1]]
    bg = tuple(sum(c[i] for c in corners) // 4 for i in range(3))

    def pixel(x, y):
        r, g, b = px[x, y]
        if abs(r - bg[0]) + abs(g - bg[1]) + abs(b - bg[2]) < 110:
            return None
        return (r << 16) | (g << 8) | b

    return cells_of([[pixel(x, y) for x in range(SIZE)] for y in range(SIZE)])


def bake_grid(path, pitch, x0, y0, cols, blocks_tall):
    """Grid pixel art: one pixel per block, read at the block's centre."""
    im = Image.open(path).convert("RGBA")
    px = im.load()

    def block(i, j):
        cx, cy = x0 + (i + 0.5) * pitch, y0 + (j + 0.5) * pitch
        if cy >= im.height:
            return None
        samples = [px[int(cx + dx), int(cy + dy)] for dx in (-3, 0, 3) for dy in (-3, 0, 3)]
        samples = sorted((s for s in samples if s[3] > 128), key=lambda s: s[0] + s[1] + s[2])
        if len(samples) < 5:
            return None
        r, g, b, _ = samples[len(samples) // 2]
        return (r << 16) | (g << 8) | b

    rows = (blocks_tall + 1) // 2
    grid = [[block(i, j) for i in range(cols)] for j in range(rows * 2)]
    return cells_of(grid), cols, rows, text_of(grid)


items = []
picks = {"gear": 99, "keys": 99, "weapons": 30}
for cls, limit in picks.items():
    per_tier = {}
    for y in sorted(glob.glob(os.path.join(ASSETS, "curated", "rewards", cls, "*.yaml"))):
        text = open(y, encoding="utf-8-sig").read()
        png = y[:-5] + ".png"
        if not os.path.exists(png):
            continue
        tier = field(text, "tier").lower() or "common"
        if cls == "weapons" and per_tier.get(tier, 0) >= 6:
            continue
        if sum(per_tier.values()) >= limit:
            break
        per_tier[tier] = per_tier.get(tier, 0) + 1
        items.append({
            "id": os.path.basename(y)[:-5],
            "name": field(text, "name"),
            "tier": tier,
            "cls": {"gear": "gear", "keys": "key", "weapons": "weapon"}[cls],
            "notes": field(text, "notes"),
            "art": bake(png),
        })

# The terminal emblem is 27 x 34 blocks of 18.6px, starting at (262.8, 207).
emblem, emblem_cols, emblem_rows, emblem_text = bake_grid(EMBLEM_PNG, 18.6, 262.8, 207, 27, 34)
with open(os.path.join(os.path.dirname(EMBLEM_PNG), "emblem.txt"), "w", encoding="utf-8") as f:
    f.write(emblem_text + "\n")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_loot.py from the XP4Life art. Do not edit by hand.\n")
    f.write("import type { LootItem } from '../types'\n\n")
    f.write(f"export const ART_COLUMNS = {SIZE}\nexport const ART_ROWS = {SIZE // 2}\n\n")
    f.write(f"export const EMBLEM = {json.dumps(emblem)}\n")
    f.write(f"export const EMBLEM_COLUMNS = {emblem_cols}\nexport const EMBLEM_ROWS = {emblem_rows}\n\n")
    f.write("export const LOOT: readonly LootItem[] = ")
    f.write(json.dumps(items, indent=1))
    f.write("\n")

tiers = {}
for i in items:
    tiers[i["tier"]] = tiers.get(i["tier"], 0) + 1
print(len(items), "items", tiers, "emblem", emblem_cols, "x", emblem_rows, os.path.getsize(OUT), "bytes")